def create_agent(
        llm,
        tool_executor,
        final_answer_generator
):
    """
    Create an IncidentAgent with lightweight fake dependencies.
    """

    return IncidentAgent(
        mcp_client=None,
        capability_registry=FakeCapabilityRegistry(),
        tool_executor=tool_executor,
        llm=llm,
        evidence_extractor=(
            FakeEvidenceExtractor()
        ),
        missing_evidence_detector=(
            FakeMissingEvidenceDetector()
        ),
        context_manager=(
            FakeContextManager()
        ),
        final_answer_generator=(
            final_answer_generator
        )

    )

@pytest.mark.asyncio
async def test_agent_executes_requested_tool():
    """
    Verify that when the LLM requests an MCP tool,
    IncidentAgent actually executes that tool.
    
    """
    tool_call=ToolCall(
    id="call_1",
    name="get_pipeline_status",
    arguments={
        "request":{
            "pipeline_name":"customer_sync"
        }
    }
)

    llm=FakeLLM(
    [

        LLMResponse(
            content=None,
            tool_calls=[tool_call],
            assistant_message={"role": "assistant", "content": None},
        ),

        LLMResponse(
            content="Investigation complete.",
            tool_calls=[],
            assistant_message={"role": "assistant", "content": "Investigation complete."},
        )

    ]

)
    tool_executor=FakeToolExecutor(
    results={
        "get_pipeline_status":{
            "found":True,
            "pipeline":{
                "name":"customer_sync"
            },
            "latest_run":{
                "status":"FAILED"
            }
        }
    }
)
    final_answer_generator=(
    FakeFinalAnswerGenerator()
)

    agent=create_agent(
    llm=llm,
    tool_executor=tool_executor,
    final_answer_generator=final_answer_generator
)

    await agent.run(
    "customer_sync",
    "Why did customer_sync fail ?",
)

    assert len(tool_executor.calls)==1
    assert (
    tool_executor.calls[0]["tool_name"]=="get_pipeline_status"
)
    assert (
    tool_executor.calls[0]["arguments"]
    == {
        "request": {
            "pipeline_name": "customer_sync"
        }
    }
)

