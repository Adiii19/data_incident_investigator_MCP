@pytest.mark.asyncio
async def test_agent_recovers_from_tool_failure():
    """
    Verify that a ToolExecutorError does not immediately 
    terminate the investigation.
    
    """

    tool_call=ToolCall(
        id="call_1",
        name="get_pipeline_logs",
        arguments={
            "request":{
                "pipeline_name":"customer_sync"
            }
        }
    )

    llm=FakeLLM(
        [
                LLMResponse(
                content=None,
                tool_calls=[tool_call],
                assistant_message={"role": "assistant", "content": None},
            ),

            LLMResponse(
                content="Investigation complete.",
                tool_calls=[],
                assistant_message={"role": "assistant", "content": "Investigation complete."},
            ),
        ]
    )

    tool_failure=ToolExecutionError(
        tool_name="get_pipeline_logs",
        message="Simulated timeout"
    )

    tool_executor=FakeToolExecutor(
        results={
            "get_pipeline_logs":tool_failure
        }
    )

    final_answer_generator = (
        FakeFinalAnswerGenerator()
    )

    agent = create_agent(
        llm=llm,
        tool_executor=tool_executor,
        final_answer_generator=(
            final_answer_generator
        ),
    )

    result=await agent.run(
        "customer_sync",
        "Investigate customer_sync"
    )

    assert final_answer_generator.called

    assert(
        result=="Final investigation report."
    )


@pytest.mark.asyncio
async def test_agent_calls_final_answer_generator():
    """
    Verify that when the LLM produces a response without
    tool calls, the agent invokes the FinalAnswerGenerator.
    """

    llm=FakeLLM(
        [
            LLMResponse(
                content="I have enough evidence",
                tool_calls=[]

            )
        ]
    )

    tool_executor=FakeToolExecutor()

    final_answer_generator=(
        FakeFinalAnswerGenerator(
            response=(
                "Structured final investigation"
            )
        )
    )

    agent=create_agent(
        llm=llm,
        tool_executor=tool_executor,
        final_answer_generator=final_answer_generator
    )

    result=await agent.run(
        "customer_sync",
        "why did customer_sync fail ?"
    )

    assert final_answer_generator.called

    assert(
        result=="Structured final investigation"
    )

    assert len(
        final_answer_generator.states
    )==1
    














